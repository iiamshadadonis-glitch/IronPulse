import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {resolve,join,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {parse} from '@babel/parser';

const hash=value=>createHash('sha256').update(value).digest('hex');
export function createAssetManifest(root){
  const directory=join(root,'public'),files=[];
  function walk(folder){for(const entry of readdirSync(folder,{withFileTypes:true})){const path=join(folder,entry.name);if(entry.isDirectory())walk(path);else if(entry.isFile()&&/\.(?:css|js)$/.test(entry.name))files.push(path);}}
  walk(directory);files.sort();
  const assets={},imports=new Set();
  for(const file of files){
    const path='/'+relative(directory,file).replaceAll('\\','/'),body=readFileSync(file);
    assets[path]=hash(body).slice(0,20);
    if(!file.endsWith('.js'))continue;
    const tree=parse(body.toString('utf8'),{sourceType:'unambiguous'});
    function visit(node){
      if(!node||typeof node!=='object')return;
      const source=['ImportDeclaration','ExportNamedDeclaration','ExportAllDeclaration'].includes(node.type)?node.source:node.type==='CallExpression'&&node.callee?.type==='Import'?node.arguments[0]:node.type==='ImportExpression'?node.source:null;
      if(source?.type==='StringLiteral'&&/^(?:\.{1,2}\/|\/(?!\/))/.test(source.value)){
        const target=new URL(source.value,'https://assets.invalid'+path);
        if(/\.js$/.test(target.pathname))imports.add(target.pathname+target.search);
      }
      for(const [key,value]of Object.entries(node)){if(['loc','extra','comments'].includes(key))continue;if(Array.isArray(value))value.forEach(visit);else if(value&&typeof value==='object')visit(value);}
    }
    visit(tree);
  }
  const version=JSON.parse(readFileSync(join(root,'public/release.json'),'utf8')).version;
  const build=hash(JSON.stringify({version,assets})).slice(0,20);
  const modules=[...imports].sort().filter(path=>assets[new URL(path,'https://assets.invalid').pathname]);
  return {version,build,assets,modules};
}
export function buildGymAssets(root){
  const manifest=createAssetManifest(root),target=join(root,'functions/_lib/gym-asset-manifest.js');
  const output='// Generated by npm run build:assets. Keep source CSS/JS unchanged.\nexport default '+JSON.stringify(manifest,null,2)+';\n';
  let previous='';try{previous=readFileSync(target,'utf8');}catch{}
  if(previous!==output)writeFileSync(target,output);
  return manifest;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const manifest=buildGymAssets(fileURLToPath(new URL('../',import.meta.url)));
  console.log('IronPulse '+manifest.version+' asset build '+manifest.build+': '+Object.keys(manifest.assets).length+' CSS/JS files fingerprinted; '+manifest.modules.length+' module dependency URLs versioned.');
}
