const legacy=normalizeAutomaticEmailTemplates({invoice:{body:'Legacy message'}});
assert.equal(legacy.invoice.intro,'Legacy message');
assert.match(legacy.invoice.footerBody,/Thank you/);
const saved=normalizeAutomaticEmailTemplates({invoice:{intro:'Before',footerBody:'After @BrandName',summaryLabels:['One','Two','Three','Four']}});
const roundTrip=normalizeAutomaticEmailTemplates(saved),rendered=applyEmailTemplate(roundTrip.invoice,{BrandName:'Example',ClientName:'Customer'});
assert.equal(roundTrip.invoice.footerBody,'After @BrandName');
assert.equal(rendered.body,'After Example');
assert.match(rendered.greeting,/Customer/);
console.log('V16.99 smoke checks passed.');
