import fs from 'node:fs';
import assert from 'node:assert/strict';
import {normalizeAutomaticEmailTemplates,applyEmailTemplate} from '../functions/_lib/automatic-email-templates.js';

const read=path=>fs.readFileSync(new URL(`../${path}`,import.meta.url),'utf8');
const index=read('public/admin/index.html');
const ui=read('public/admin/final-v16-99-visitors-email-studio.js');
const css=read('public/admin/final-v16-99-visitors-email-studio.css');
const visitor=read('functions/api/admin/visitor-info.js');
const templates=read('functions/_lib/automatic-email-templates.js');
const endpoint=read('functions/api/admin/automatic-email-templates.js');
const documents=read('functions/api/admin/client-documents.js');
const suite=read('functions/_lib/marketing-suite.js');
const recovery=read('functions/_lib/payment-recovery.js');
const utils=read('functions/_lib/utils.js');

assert.match(index,/final-v16-99-visitors-email-studio\.css\?v=16\.99/);
assert.match(index,/final-v16-99-visitors-email-studio\.js\?v=16\.99/);
const identity=ui.slice(ui.indexOf('function visitorIdentity'),ui.indexOf('function visitorRows'));
assert.ok(identity.indexOf('IP Address:')<identity.indexOf('Location:'),'IP must appear before location');
assert.ok(identity.indexOf('Location:')<identity.indexOf('Device ID:'),'location must appear before device ID');
assert.match(ui,/Download Excel/);
assert.match(ui,/application\/vnd\.ms-excel/);
assert.match(ui,/analytics_consent/);
assert.match(ui,/ads_consent/);
assert.match(visitor,/resultLimit=exporting\?5000:250/);
assert.match(visitor,/l\.location/);
assert.match(visitor,/analytics_consent/);
assert.match(visitor,/ads_consent/);
assert.match(ui,/data-preview-email/);
assert.match(ui,/data-save-email/);
assert.match(ui,/Email Message — Before Summary/);
assert.match(ui,/Email Message — After Summary/);
assert.match(ui,/Footer Capsule \/ Note/);
assert.match(ui,/Button Destination/);
assert.match(ui,/emailArrow='<span[^']+<svg/);
assert.doesNotMatch(ui,/uc98-email-arrow[^\n]*⌄/);
assert.match(css,/summary::marker\{content:''\}/);
assert.match(css,/uc99-email-preview iframe/);
for(const key of ['schedule_confirmation','meeting_reminder','invoice','payment_statement','payment_success','payment_failed'])assert.match(templates,new RegExp(`${key}:`));
assert.match(endpoint,/action==='preview'/);
assert.match(endpoint,/action==='save_one'/);
assert.match(endpoint,/brandedEmailHtml/);
assert.match(documents,/automaticEmailSummaryRows/);
